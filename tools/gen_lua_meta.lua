-- Writes LuaLS definition files for the nex module by looking at what the bindings actually registered, so editors know the
-- global "nex" and every class, method, field and constant without anyone keeping a second list by hand. We write one file per
-- library: nex.lua for the core, and crypto.lua, pead.lua and so on for each namespace the build includes.
-- Run it through the test runner: nex_lua_test tools/gen_lua_meta.lua <output directory>

local outDir = assert(arg and arg[1], "usage: gen_lua_meta.lua <output directory>")

-- Libraries that live under their own namespace in the module, such as nex.crypto. Ones the build left out are skipped.
local LIBRARIES = { "crypto", "pead", "pia" }

local function sortedKeys(t)
    local keys = {}
    for k in pairs(t) do
        if type(k) == "string" then
            keys[#keys + 1] = k
        end
    end
    table.sort(keys)
    return keys
end

-- Every class metatable in the registry has the __methods, __fields and __is tables that DefineClass builds
local classes = {}
for name, mt in pairs(debug.getregistry()) do
    if type(name) == "string" and type(mt) == "table" and type(mt.__methods) == "table" and type(mt.__is) == "table" then
        classes[name] = mt
    end
end

-- The direct base is the ancestor with the most ancestors of its own, because __is holds the whole chain
local function directBase(name)
    local best, depth = nil, -1
    for ancestor in pairs(classes[name].__is) do
        if ancestor ~= name and classes[ancestor] then
            local n = 0
            for _ in pairs(classes[ancestor].__is) do
                n = n + 1
            end
            if n > depth then
                best, depth = ancestor, n
            end
        end
    end
    return best
end

local function ownKeys(name, key)
    local base = directBase(name)
    local inherited = base and classes[base][key] or {}
    local keys = {}
    for _, k in ipairs(sortedKeys(classes[name][key])) do
        if inherited[k] == nil then
            keys[#keys + 1] = k
        end
    end
    return keys
end

-- Each class goes in the file of the namespace that holds its constructor, and everything else goes in nex.lua
local owner = {}
local namespaces = {}
for _, lib in ipairs(LIBRARIES) do
    local ns = rawget(nex, lib)
    if type(ns) == "table" then
        namespaces[#namespaces + 1] = lib
        for _, member in ipairs(sortedKeys(ns)) do
            if classes[member] then
                owner[member] = lib
            end
        end
    end
end

local function newFile(lib)
    local lines = { "---@meta " .. lib, "-- This file is generated by tools/gen_lua_meta.lua during the build. Don't edit it by hand.", "" }
    return lines, function(s)
        lines[#lines + 1] = s
    end
end

local function emitClasses(emit, lib)
    for _, name in ipairs(sortedKeys(classes)) do
        if (owner[name] or "nex") == lib then
            local base = directBase(name)
            emit(("---@class nex.%s%s"):format(name, base and (" : nex." .. base) or ""))
            for _, field in ipairs(ownKeys(name, "__fields")) do
                emit(("---@field %s any"):format(field))
            end
            local var = "nex_" .. name
            emit(("local %s = {}"):format(var))
            for _, method in ipairs(ownKeys(name, "__methods")) do
                emit("---@return any")
                emit(("function %s:%s(...) end"):format(var, method))
            end
            emit("")
        end
    end
end

-- Writes a table of the module, such as nex.CallContext or nex.crypto, with its functions, classes and constants
local function emitTable(emit, path, value)
    for _, member in ipairs(sortedKeys(value)) do
        if member ~= "__new" then
            local v = value[member]
            if type(v) == "function" then
                emit("---@return any")
                emit(("function %s.%s(...) end"):format(path, member))
            elseif type(v) == "table" and rawget(v, "__new") ~= nil and classes[member] then
                emit(("---@overload fun(...): nex.%s"):format(member))
                emit(("%s.%s = {}"):format(path, member))
            elseif math.type(v) == "integer" then
                emit(("%s.%s = %d"):format(path, member, v))
            else
                emit(("%s.%s = nil ---@type any"):format(path, member))
            end
        end
    end
end

local function write(lib, lines)
    local file = assert(io.open(outDir .. "/" .. lib .. ".lua", "w"))
    file:write(table.concat(lines, "\n"))
    file:close()
end

local isNamespace = {}
for _, lib in ipairs(namespaces) do
    isNamespace[lib] = true
end

local lines, emit = newFile("nex")
emitClasses(emit, "nex")
emit("---@class nexlib")
local module = {}
for _, key in ipairs(sortedKeys(nex)) do
    if type(nex[key]) == "function" then
        emit(("---@field %s fun(...): any"):format(key))
    elseif not isNamespace[key] then
        module[#module + 1] = key
    end
end
emit("nex = {}")
emit("")
for _, key in ipairs(module) do
    local value = nex[key]
    if type(value) == "table" and rawget(value, "__new") ~= nil and classes[key] then
        emit(("---@overload fun(...): nex.%s"):format(key))
    end
    emit(("nex.%s = {}"):format(key))
    if type(value) == "table" then
        emitTable(emit, "nex." .. key, value)
    end
    emit("")
end
write("nex", lines)

for _, lib in ipairs(namespaces) do
    local libLines, libEmit = newFile(lib)
    emitClasses(libEmit, lib)
    libEmit(("nex.%s = {}"):format(lib))
    emitTable(libEmit, "nex." .. lib, nex[lib])
    libEmit("")
    write(lib, libLines)
end
