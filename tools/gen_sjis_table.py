#!/usr/bin/env python3
# We build the Shift JIS tables StringUtil converts with from Python's cp932 codec, so the table matches the code page the Wii U uses.
# We run it by hand from the repository root, since the build only reads the table it wrote.
import pathlib

pairs = []
for lead in range(0x81, 0xFD):
    if 0xA0 <= lead <= 0xDF:
        continue
    for trail in range(0x40, 0xFD):
        if trail == 0x7F:
            continue
        try:
            text = bytes([lead, trail]).decode("cp932")
        except UnicodeDecodeError:
            continue
        if len(text) != 1:
            continue
        pairs.append(((lead << 8) | trail, ord(text)))

# Several cp932 codes decode to the same character, so we keep the first one when encoding, as Windows does.
encode = {}
for sjis, uni in pairs:
    encode.setdefault(uni, sjis)


def emit(name, rows):
    lines = [f"    constexpr SjisPair {name}[] = {{"]
    for i in range(0, len(rows), 8):
        chunk = ", ".join(f"{{0x{a:04X}, 0x{b:04X}}}" for a, b in rows[i:i + 8])
        lines.append(f"        {chunk},")
    lines.append("    };")
    return "\n".join(lines)


out = [
    "// This file is generated by tools/gen_sjis_table.py.",
    "",
    "namespace",
    "{",
    "    struct SjisPair",
    "    {",
    "        pead::u16 key;",
    "        pead::u16 value;",
    "    };",
    "",
    emit("cSjisToUnicode", sorted(pairs)),
    "",
    emit("cUnicodeToSjis", sorted(encode.items())),
    "",
    "} // namespace",
    "",
]
pathlib.Path("libs/pead/src/peadSjisTable.inc").write_text("\n".join(out))
print(len(pairs), len(encode))
